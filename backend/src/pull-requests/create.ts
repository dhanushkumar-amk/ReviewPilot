/**
 * create.ts
 * Implements creation of a pull request from an approved FixProposal.
 * Enforces strict branch name patterns, allowed file paths, line ending preservation,
 * stale HEAD detection, risk validation, Gitleaks scan, and atomic rollback on failure.
 */

import crypto from "node:crypto";
import { validateReplacement } from "../ai/patch.js";
import { prisma } from "../db.js";
import { githubApp } from "../github/app.js";
import {
  assertAllowedFilePath,
  assertSafeBranchName,
  SecurityGuardError,
  sanitizeText,
} from "../github/guards.js";
import { checkSecrets } from "../validation/static/secrets.js";

export interface CreateFixPullRequestOptions {
  fixProposalId: string;
  user: {
    id: string;
    role?: string;
  };
  workspace: {
    id: string;
  };
  acknowledgeRisk?: boolean;
}

export function buildPrBody(options: {
  findingTitle: string;
  tool: string;
  ruleId: string;
  filePath: string;
  sanitizedExplanation: string;
  validationStatus: string;
  testsRun: boolean;
  riskLevel: string;
}): string {
  const {
    findingTitle,
    tool,
    ruleId,
    filePath,
    sanitizedExplanation,
    validationStatus,
    testsRun,
    riskLevel,
  } = options;

  return [
    `## ReviewPilot Fix Proposal`,
    ``,
    `This pull request addresses finding **${findingTitle}** (${tool} rule \`${ruleId}\`) in \`${filePath}\`.`,
    ``,
    `### Explanation`,
    sanitizedExplanation || `Automated fix generated by ReviewPilot.`,
    ``,
    `### Validation Summary`,
    `- **Static Verification:** ${validationStatus}`,
    `- **Tests Executed:** ${testsRun ? "Passed" : "Not run (Static checks only)"}`,
    `- **Risk Level:** ${riskLevel}`,
    ``,
    `---`,
    `*Created automatically by [ReviewPilot](https://reviewpilot.dev). Human review and merge required.*`,
  ].join("\n");
}

export async function createFixPullRequest(options: CreateFixPullRequestOptions) {
  const { fixProposalId, user, workspace, acknowledgeRisk } = options;

  // 1. Load FixProposal within workspace
  const fixProposal = await prisma.fixProposal.findFirst({
    where: {
      id: fixProposalId,
      workspaceId: workspace.id,
    },
    include: {
      finding: {
        include: {
          repository: {
            include: {
              installation: true,
            },
          },
        },
      },
    },
  });

  if (!fixProposal) {
    throw new SecurityGuardError("NOT_FOUND", "Fix proposal not found");
  }

  // 2. Proposal must be DRAFT
  if (fixProposal.status !== "DRAFT") {
    throw new SecurityGuardError(
      "PROPOSAL_NOT_DRAFT",
      `Fix proposal is in status ${fixProposal.status}, only DRAFT proposals can create a pull request`
    );
  }

  // 3. Idempotency: Return existing pull request if already created
  const existingPr = await prisma.pullRequest.findUnique({
    where: { fixProposalId },
  });
  if (
    existingPr &&
    (existingPr.status === "OPEN" ||
      existingPr.status === "MERGED" ||
      existingPr.status === "CREATING")
  ) {
    return { pullRequest: existingPr, alreadyExists: true };
  }

  // 4. Latest FixValidation must be PASSED or PASSED_WITH_WARNINGS
  const latestValidation = await prisma.fixValidation.findFirst({
    where: {
      fixProposalId,
      workspaceId: workspace.id,
    },
    orderBy: { createdAt: "desc" },
  });

  if (
    !latestValidation ||
    (latestValidation.status !== "PASSED" &&
      latestValidation.status !== "PASSED_WITH_WARNINGS")
  ) {
    throw new SecurityGuardError(
      "PR_BLOCKED_VALIDATION",
      `Fix proposal validation must be PASSED or PASSED_WITH_WARNINGS (current: ${
        latestValidation?.status ?? "NONE"
      })`
    );
  }

  // 5. Risk Gate: HIGH risk requires role owner or admin AND acknowledgeRisk: true
  const riskLevel = latestValidation.riskLevel || "LOW";
  if (riskLevel === "HIGH") {
    const isOwnerOrAdmin = user.role === "owner" || user.role === "admin";
    if (!isOwnerOrAdmin) {
      throw new SecurityGuardError(
        "FORBIDDEN",
        "HIGH risk fix proposals can only be converted to pull requests by workspace owners or admins"
      );
    }
    if (!acknowledgeRisk) {
      throw new SecurityGuardError(
        "PR_RISK_ACK_REQUIRED",
        "HIGH risk fix proposal requires explicit risk acknowledgment"
      );
    }
  }

  // 6. Enforce safe file path
  assertAllowedFilePath(fixProposal.filePath);

  // 7. Abuse limits: 10 PRs per UTC day per workspace
  const now = new Date();
  const startOfDay = new Date(
    Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate())
  );
  const prsToday = await prisma.pullRequest.count({
    where: {
      workspaceId: workspace.id,
      createdAt: { gte: startOfDay },
      status: { not: "FAILED" },
    },
  });

  if (prsToday >= 10) {
    throw new SecurityGuardError(
      "PR_LIMIT_REACHED",
      "Workspace daily pull request limit reached (maximum 10 pull requests per day)"
    );
  }

  const { finding } = fixProposal;
  const repo = finding.repository;

  if (!repo.installation) {
    throw new SecurityGuardError(
      "REPOSITORY_NOT_CONNECTED",
      "Repository GitHub installation is not connected"
    );
  }

  const slashIndex = repo.fullName.indexOf("/");
  if (slashIndex === -1) {
    throw new SecurityGuardError("INVALID_REPO", "Invalid repository full name");
  }
  const owner = repo.fullName.slice(0, slashIndex);
  const repoName = repo.fullName.slice(slashIndex + 1);

  // 8. Permission preflight: App must have contents: write and pull_requests: write
  const installationIdNum = Number(repo.installation.installationId);
  try {
    const instRes = await githubApp.octokit.rest.apps.getInstallation({
      installation_id: installationIdNum,
    });
    const perms = (instRes.data.permissions || {}) as Record<string, string>;
    if (perms.contents !== "write" || perms.pull_requests !== "write") {
      throw new SecurityGuardError(
        "GITHUB_PERMISSION_MISSING",
        "GitHub App lacks required write permissions for contents or pull_requests"
      );
    }
  } catch (err: any) {
    if (err instanceof SecurityGuardError) throw err;
    if (
      err.status === 403 ||
      err.message?.includes("Resource not accessible by integration")
    ) {
      throw new SecurityGuardError(
        "GITHUB_PERMISSION_MISSING",
        "GitHub App integration lacks required repository permissions"
      );
    }
    throw err;
  }

  const octokit = await githubApp.getInstallationOctokit(installationIdNum);

  // 9. Stale Protection: fetch file from default branch HEAD
  let fileRes: any;
  try {
    fileRes = await octokit.rest.repos.getContent({
      owner,
      repo: repoName,
      path: fixProposal.filePath,
      ref: repo.defaultBranch,
    });
  } catch (err: any) {
    if (err.status === 404) {
      throw new SecurityGuardError(
        "STALE_FIX",
        `Target file '${fixProposal.filePath}' not found on default branch HEAD`
      );
    }
    throw err;
  }

  if (Array.isArray(fileRes.data) || fileRes.data.type !== "file") {
    throw new SecurityGuardError("INVALID_FILE_TYPE", "Target path is not a file");
  }

  if (fileRes.data.size > 1_000_000) {
    throw new SecurityGuardError(
      "FILE_TOO_LARGE",
      "File size exceeds 1 MB limit for automated fixes"
    );
  }

  const rawFileContent = Buffer.from(fileRes.data.content, "base64").toString(
    "utf8"
  );
  const fileSha = fileRes.data.sha;

  // Detect line ending & trailing newline
  const isCrlf = rawFileContent.includes("\r\n");
  const lineEnding = isCrlf ? "\r\n" : "\n";
  const hasTrailingNewline = rawFileContent.endsWith("\n");

  const lines = rawFileContent.split(/\r?\n/);
  const startIdx = fixProposal.startLine - 1;
  const count = fixProposal.endLine - fixProposal.startLine + 1;

  if (startIdx < 0 || startIdx + count > lines.length) {
    throw new SecurityGuardError(
      "STALE_FIX",
      "File lines have shifted or file is shorter than expected"
    );
  }

  const currentSlice = lines
    .slice(startIdx, startIdx + count)
    .join("\n")
    .replace(/\r/g, "");
  const expectedSlice = fixProposal.originalCode.replace(/\r/g, "");

  if (currentSlice.trim() !== expectedSlice.trim()) {
    throw new SecurityGuardError(
      "STALE_FIX",
      "Target code has changed on the default branch since the fix was drafted"
    );
  }

  // Apply replacement preserving line endings
  const replacementLines = fixProposal.replacementCode.split(/\r?\n/);
  lines.splice(startIdx, count, ...replacementLines);
  let patchedContent = lines.join(lineEnding);
  if (hasTrailingNewline && !patchedContent.endsWith(lineEnding)) {
    patchedContent += lineEnding;
  }

  // 10. Re-verify replacement constraints & secrets on patched content
  const replVal = validateReplacement({
    filePath: fixProposal.filePath,
    startLine: fixProposal.startLine,
    endLine: fixProposal.endLine,
    newCode: fixProposal.replacementCode,
    windowStart: Math.max(1, fixProposal.startLine - 10),
    windowEnd: fixProposal.endLine + 10,
    totalLines: lines.length,
  });
  if (!replVal.valid) {
    throw new SecurityGuardError(
      "PR_BLOCKED_VALIDATION",
      replVal.reason || "Replacement failed validation"
    );
  }

  const secretRes = await checkSecrets({
    filePath: fixProposal.filePath,
    patchedContent,
  });
  if (secretRes.status === "FAILED") {
    throw new SecurityGuardError(
      "PR_BLOCKED_SECRET",
      "Patch introduces potential secrets"
    );
  }

  // 11. Generate branch name reviewpilot/fix-<6-12 chars>-<4-8 chars>
  const cleanId = fixProposal.id.toLowerCase().replace(/[^a-z0-9]/g, "").slice(0, 8);
  const rand = crypto.randomBytes(3).toString("hex");
  const branchName = `reviewpilot/fix-${cleanId}-${rand}`;
  assertSafeBranchName(branchName);

  // 12. Create DB record in CREATING state
  // If a previous failed PR existed, upsert or create
  const prRecord = await prisma.pullRequest.upsert({
    where: { fixProposalId },
    create: {
      workspaceId: workspace.id,
      repositoryId: repo.id,
      findingId: finding.id,
      fixProposalId: fixProposal.id,
      validationId: latestValidation.id,
      branchName,
      baseBranch: repo.defaultBranch,
      title: `fix: ${finding.title.slice(0, 70)}`,
      status: "CREATING",
      riskLevel,
      testsRun: latestValidation.testsRun,
      createdByUserId: user.id,
    },
    update: {
      branchName,
      baseBranch: repo.defaultBranch,
      title: `fix: ${finding.title.slice(0, 70)}`,
      status: "CREATING",
      riskLevel,
      testsRun: latestValidation.testsRun,
      errorCode: null,
      githubNumber: null,
      htmlUrl: null,
      headSha: null,
      createdByUserId: user.id,
    },
  });

  let branchCreated = false;

  try {
    // 13. Get default branch HEAD SHA
    const refData = await octokit.rest.git.getRef({
      owner,
      repo: repoName,
      ref: `heads/${repo.defaultBranch}`,
    });
    const baseSha = refData.data.object.sha;

    // 14. Create branch
    await octokit.rest.git.createRef({
      owner,
      repo: repoName,
      ref: `refs/heads/${branchName}`,
      sha: baseSha,
    });
    branchCreated = true;

    // 15. Commit patched file
    const commitMsg = `fix: ${finding.title.slice(0, 60)} (ReviewPilot)`;
    await octokit.rest.repos.createOrUpdateFileContents({
      owner,
      repo: repoName,
      path: fixProposal.filePath,
      message: commitMsg,
      content: Buffer.from(patchedContent, "utf8").toString("base64"),
      branch: branchName,
      sha: fileSha,
    });

    // 16. Open PR
    const sanitizedExplanation = sanitizeText(fixProposal.explanation, 600);
    const prBody = buildPrBody({
      findingTitle: finding.title,
      tool: finding.tool,
      ruleId: finding.ruleId,
      filePath: fixProposal.filePath,
      sanitizedExplanation,
      validationStatus: latestValidation.status,
      testsRun: latestValidation.testsRun,
      riskLevel,
    });

    const prRes = await octokit.rest.pulls.create({
      owner,
      repo: repoName,
      title: `fix: ${finding.title.slice(0, 70)}`,
      head: branchName,
      base: repo.defaultBranch,
      body: prBody,
    });

    // 17. Update DB record to OPEN
    const updatedPr = await prisma.pullRequest.update({
      where: { id: prRecord.id },
      data: {
        status: "OPEN",
        githubNumber: prRes.data.number,
        htmlUrl: prRes.data.html_url,
        headSha: prRes.data.head.sha,
        lastSyncedAt: new Date(),
      },
    });

    // 18. Audit log
    await prisma.auditLog.create({
      data: {
        workspaceId: workspace.id,
        actorUserId: user.id,
        action: "PULL_REQUEST_CREATED",
        targetType: "PULL_REQUEST",
        targetId: updatedPr.id,
        metadata: {
          prNumber: prRes.data.number,
          branchName,
          repositoryFullName: repo.fullName,
          findingId: finding.id,
        },
      },
    });

    return { pullRequest: updatedPr, alreadyExists: false };
  } catch (err: any) {
    // Atomic rollback: compensation on failure
    if (branchCreated) {
      try {
        assertSafeBranchName(branchName);
        await octokit.rest.git.deleteRef({
          owner,
          repo: repoName,
          ref: `heads/${branchName}`,
        });
      } catch {
        // ignore branch deletion error during rollback
      }
    }

    const errCode =
      err.code ||
      (err.status === 403 ? "GITHUB_PERMISSION_MISSING" : "PR_CREATION_FAILED");

    await prisma.pullRequest.update({
      where: { id: prRecord.id },
      data: {
        status: "FAILED",
        errorCode: errCode,
      },
    });

    await prisma.auditLog.create({
      data: {
        workspaceId: workspace.id,
        actorUserId: user.id,
        action: "PULL_REQUEST_FAILED",
        targetType: "PULL_REQUEST",
        targetId: prRecord.id,
        metadata: {
          errorCode: errCode,
          branchName,
          repositoryFullName: repo.fullName,
        },
      },
    });

    throw err;
  }
}
